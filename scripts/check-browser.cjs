const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true,channel:'chrome'});
 const page = await browser.newPage({viewport:{width:390,height:844}, serviceWorkers:'block'});
 const errors=[]; page.on('pageerror', e => errors.push(e.message));
 let posts=0;
 await page.route('https://api.wanikani.com/v2/**', async route => {
   const url=new URL(route.request().url()); let data;
   if(url.pathname.endsWith('/user')) data={data:{preferences:{}}};
   else if(url.pathname.endsWith('/assignments')) data={data:[{id:1,data:{subject_id:1,srs_stage:1,available_at:'2020-01-01T00:00:00Z'}}]};
   else if(url.pathname.endsWith('/subjects')) data={data:[{id:1,object:'vocabulary',data:{characters:'仮名',meanings:[{meaning:'Kana',accepted_answer:true}],readings:[{reading:'かな',accepted_answer:true}]}}]};
   else if(url.pathname.endsWith('/study_materials')) data={data:[]};
   else if(url.pathname.endsWith('/reviews')) {
      posts++;
      assert.deepEqual(JSON.parse(route.request().postData()).review,{subject_id:1,incorrect_meaning_answers:1,incorrect_reading_answers:0});
      if(posts===1) return route.fulfill({status:503,body:'{}'});
      data={data:{}};
   } else throw new Error('unexpected '+url);
   await route.fulfill({json:data});
 });
 await page.goto('http://localhost:4173');
 await page.locator('#api-token').fill('test-token');
 await page.locator('#api-token').press('Enter');
 await page.locator('#quick-btn').click();
 await page.locator('#answer-input').waitFor({state:'visible'});
 await page.locator('#menu-btn').click();
 assert.equal(await page.locator('#menu').isVisible(),true);
 await page.locator('#stats-btn').click();
 await page.locator('#stats-back-btn').click();
 await page.locator('#answer-input').pressSequentially('kana');
 assert.equal(await page.locator('#answer-input').inputValue(),'kana');
 await page.locator('#answer-input').press('Enter');
 assert.equal(await page.locator('#result-text').textContent(),'Correct!');
 await page.keyboard.press('Enter');
 await page.locator('#answer-input').fill('wrong');
 await page.locator('#submit-btn').click();
 await page.locator('#result-primary-btn').click();
 await page.locator('#answer-input').fill('kana');
 await page.locator('#submit-btn').click();
 await page.locator('#result-primary-btn').click();
 await page.getByText('Retry save',{exact:true}).waitFor();
 assert.match(await page.locator('#save-error').textContent(),/503/);
 await page.locator('#result-primary-btn').click();
 await page.getByText('Session complete!',{exact:true}).waitFor();
 assert.equal(posts,2);
 assert.equal(await page.locator('#answer-input').isVisible(),false);
 assert.equal(await page.locator('#progress').textContent(),'1/1 completed');
 await page.locator('#menu-btn').click();
 await page.locator('#stats-btn').click();
 assert.equal(await page.locator('#total-reviews').textContent(),'3');
 await page.locator('#stats-back-btn').click();
 await page.screenshot({path:require('node:path').join(require('node:os').tmpdir(), 'takashika-mobile.png'),fullPage:true});
 await page.locator('#menu-btn').click();
 await page.locator('#logout-btn').click();
 assert.equal(await page.locator('#login-screen').isVisible(),true);
 assert.equal(await page.evaluate(()=>localStorage.getItem('wanikani_api_token')),null);
 assert.deepEqual(errors,[]);
 await page.setViewportSize({width:1440,height:900});
 await page.screenshot({path:require('node:path').join(require('node:os').tmpdir(), 'takashika-desktop.png'),fullPage:true});
 console.log('Browser checks passed: login, menu, stats, romaji typing, keyboard, wrong/correct answers, failed-save retry, completion, logout; no page errors.');

 // Empty queues and image-only radicals.
 const edge = await browser.newPage({serviceWorkers:'block', viewport:{width:390,height:844}});
 let radical = false;
 edge.on('pageerror', e => errors.push(e.message));
 await edge.route('https://api.wanikani.com/v2/**', async route => {
   const path = new URL(route.request().url()).pathname;
   let data = [];
   if (path.endsWith('/user')) data = {preferences:{}};
   if (path.endsWith('/assignments') && radical) data = [{id:2,data:{subject_id:2,srs_stage:1,available_at:'2020-01-01T00:00:00Z'}}];
   if (path.endsWith('/subjects')) data = [{id:2,object:'radical',data:{slug:'secret-answer',characters:null,
     character_images:[{content_type:'image/svg+xml',url:'http://localhost:4173/icons/app-icon.svg'}],
     meanings:[{meaning:'Example',accepted_answer:true}]}}];
   await route.fulfill({json:{data}});
 });
 await edge.goto('http://localhost:4173');
 await edge.locator('#api-token').fill('test');
 await edge.locator('#login-btn').click();
 await edge.getByText("You're all caught up.",{exact:true}).waitFor();
 assert.equal(await edge.locator('#submit-btn').isVisible(),false);
 assert.equal(await edge.locator('#quick-btn').isDisabled(),true);
 radical = true;
 await edge.locator('#home-refresh-btn').click();
 await edge.locator('#quick-btn').click();
 await edge.locator('.radical-image').waitFor();
 assert.equal(await edge.locator('#question-text').textContent(),'');
 assert.equal(await edge.locator('#task-mode-label').textContent(),'Radical Name');
 await edge.screenshot({path:require('node:path').join(require('node:os').tmpdir(), 'takashika-radical.png')});
 await edge.close();
 const offline = await browser.newContext();
 const shell = await offline.newPage();
 await shell.goto('http://localhost:4173');
 await shell.evaluate(async () => {
   await caches.open('unrelated-app-cache');
   await navigator.serviceWorker.ready;
 });
 await shell.reload();
 await shell.waitForFunction(() => Boolean(navigator.serviceWorker.controller));
 assert.equal(await shell.evaluate(() => caches.has('unrelated-app-cache')), true);
 await offline.setOffline(true);
 await shell.reload();
 await shell.locator('#login-btn').waitFor();
 await shell.locator('#api-token').fill('test');
 await shell.locator('#login-btn').click();
 await shell.locator('#login-error').filter({hasText:'Connection failed'}).waitFor();
 await offline.close();
 assert.deepEqual(errors,[]);
 console.log('Edge checks passed: empty state layout, refresh, image-only radical without answer leakage, offline app shell and unrelated cache preservation.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
